
 Jair Bolsonaro - Trajetória Política

## Descrição

Este projeto consiste em uma página informativa sobre Jair Messias Bolsonaro, apresentando aspectos de sua biografia, trajetória política, eleição presidencial e período como presidente do Brasil.

O conteúdo possui finalidade educacional e busca apresentar informações de forma organizada e objetiva.

## Tema escolhido

O tema escolhido foi:

**Jair Bolsonaro e sua trajetória política.**

